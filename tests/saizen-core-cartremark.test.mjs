  assert.equal(SZ.cartRemarkKind([null, undefined, '']), 'none');
  assert.equal(SZ.cartRemarkKind(['조식 추가', '']), 'none');
  assert.equal(SZ.cartQtyFromRemark([null, '전동카트 3대']), 3);
