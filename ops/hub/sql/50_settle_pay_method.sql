--  체크아웃 전날부터 사전정산: 각 청구건을 현금/카드로 찍고 「마감」하면
--  수단별 합계를 payments 2건으로 자동 생성 + folio status='settled' → 잔액 0.
--  · charges.pay_method = 'cash'/'card'(저장은 한글 '현금'/'카드')/null(미정).
--  · 환불/조정은 단가에 마이너스를 넣어 음수 청구 라인으로(같은 수단으로 상계).
--  · B2B(現地精算表)는 불변 — 이건 현장 御請求書 전용.
--  멱등. ⚠ Supabase SQL Editor 수동 실행 — 이미 MCP로 적용.
-- ============================================================================

alter table charges add column if not exists pay_method text;
comment on column charges.pay_method is '사전정산 표시: 현금/카드/null(미정). 마감 시 method별 합산해 payments 자동생성';
