--  · print_overrides 에 excluded 컬럼 추가. **夕食(dinner.html)만 이 값을 본다**
--    (航空カバー는 excluded 를 읽지 않으므로 팀별 시트는 그대로 출력 — 영향 없음).
--  · 분배 정합성은 화면에서 원래 합계 vs 수정 후 합계로 확인.
--  실행: Supabase SQL Editor. 32(print_overrides) 이후. 멱등.
